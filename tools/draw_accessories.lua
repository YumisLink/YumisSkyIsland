-- Spaces are intentional transparent holes, identical to dots.
-- Three non-overlapping editable layers preserve contour, material clusters and highlights.
local function rgba(hex)
  return app.pixelColor.rgba(tonumber(hex:sub(1,2),16),tonumber(hex:sub(3,4),16),tonumber(hex:sub(5,6),16),255)
end
local preview=Sprite(800,800,ColorMode.RGB)
preview.layers[1].name="Inventory preview 8x nearest pixel"
local sheet=preview.cels[1].image
local bg=app.pixelColor.rgba(23,31,45,255)
for y=0,799 do for x=0,799 do sheet:drawPixel(x,y,bg) end end
for i,item in ipairs(items) do
  assert(#item.rows==16,item.id..": requires 16 rows")
  local spr=Sprite(16,16,ColorMode.RGB)
  spr.layers[1].name="01 Contour"
  local layers={spr.layers[1],spr:newLayer(),spr:newLayer()}
  layers[2].name="02 Materials"
  layers[3].name="03 Highlights"
  local imgs={Image(16,16,ColorMode.RGB),Image(16,16,ColorMode.RGB),Image(16,16,ColorMode.RGB)}
  local used,count={},0
  for y,row in ipairs(item.rows) do
    assert(#row<=16,item.id..": row "..y.." wider than 16: "..#row)
    for x=1,#row do
      local ch=row:sub(x,x)
      if ch~="." and ch~=" " then
        local hex=assert(item.palette[ch],item.id..": missing color "..ch)
        local p=rgba(hex)
        local layer=ch=="O" and 1 or ((ch=="L" or ch=="H" or ch=="C") and 3 or 2)
        imgs[layer]:drawPixel(x-1,y-1,p)
        used[hex]=true; count=count+1
        local px=((i-1)%5)*160+16+(x-1)*8
        local py=math.floor((i-1)/5)*160+16+(y-1)*8
        for yy=0,7 do for xx=0,7 do sheet:drawPixel(px+xx,py+yy,p) end end
      end
    end
  end
  for n=1,3 do spr:newCel(layers[n],spr.frames[1],imgs[n],Point(0,0)) end
  local palette=Palette(1)
  local colors={}
  for hex in pairs(used) do colors[#colors+1]=hex end
  table.sort(colors)
  palette:resize(#colors+1)
  palette:setColor(0,Color{r=0,g=0,b=0,a=0})
  for n,hex in ipairs(colors) do palette:setColor(n,Color{r=tonumber(hex:sub(1,2),16),g=tonumber(hex:sub(3,4),16),b=tonumber(hex:sub(5,6),16),a=255}) end
  spr:setPalette(palette)
  spr:saveAs(root.."/art/accessories/"..item.id..".aseprite")
  spr:saveCopyAs(root.."/src/main/resources/assets/yumis_sky_island/textures/item/accessory/"..item.id..".png")
  print(item.id..": 16x16, "..count.." opaque pixels, "..#colors.." colors, 3 layers")
  spr:close()
end
preview:saveCopyAs(root.."/art/accessories/reference-v2/pixel-preview.png")
preview:close()
print("Created 25 transparent icons and editable Aseprite sources; 800x800 nearest-pixel preview.")
